BEGIN;

CREATE TABLE IF NOT EXISTS tickets (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 49) PRIMARY KEY,
    queue_id text NOT NULL REFERENCES queues(id),
    customer_name text NOT NULL,
    service_name text NOT NULL,
    is_priority boolean NOT NULL,
    status text NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'active', 'finished')),
    issued_at timestamptz NOT NULL DEFAULT now(),
    called_at timestamptz,
    finished_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS tickets_one_active_per_queue
    ON tickets (queue_id) WHERE status = 'active';

CREATE INDEX IF NOT EXISTS tickets_waiting_order
    ON tickets (queue_id, is_priority DESC, id) WHERE status = 'waiting';

COMMIT;
